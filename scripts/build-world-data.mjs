import { writeFile } from 'node:fs/promises';

const WIND_URL = 'https://oceanwatch.pifsc.noaa.gov/erddap/griddap/ccmp-monthly-v2-0.json';
const CURRENT_URL = 'https://oceanwatch.pifsc.noaa.gov/erddap/griddap/yearly_336c_0b32_9cd3.json';
const OUTPUT = new URL('../src/world/data/atlantic-climatology.generated.ts', import.meta.url);

const MIN_LAT = -60;
const MAX_LAT = 65;
const MIN_LON = -100;
const MAX_LON = 30;
const STEP = 5;
const LAT_COUNT = (MAX_LAT - MIN_LAT) / STEP + 1;
const LON_COUNT = (MAX_LON - MIN_LON) / STEP + 1;
const MONTHS = 12;
const COMPONENTS = 4;
const SCALE = 100;
const MISSING = -32768;
const MS_TO_KNOTS = 1.9438444924406;

const WIND_E = 0;
const WIND_N = 1;
const CURRENT_E = 2;
const CURRENT_N = 3;

function fieldIndex(month, latIndex, lonIndex, component) {
  return (((month * LAT_COUNT + latIndex) * LON_COUNT + lonIndex) * COMPONENTS) + component;
}

function targetIndex(value, min, count) {
  const rounded = Math.round((value - min) / STEP);
  return rounded >= 0 && rounded < count ? rounded : -1;
}

function normalizeLon(lon) {
  return lon > 180 ? lon - 360 : lon;
}

async function fetchRows(url, query) {
  const response = await fetch(`${url}?${query}`);
  if (!response.ok) throw new Error(`${response.status} ${response.statusText} fetching ${response.url}`);
  const payload = await response.json();
  const names = payload.table.columnNames;
  return payload.table.rows.map((row) => Object.fromEntries(names.map((name, index) => [name, row[index]])));
}

function createAccumulator() {
  const length = MONTHS * LAT_COUNT * LON_COUNT * COMPONENTS;
  return {
    sum: new Float64Array(length),
    count: new Uint32Array(length),
  };
}

function addSample(accumulator, month, lat, lon, component, valueKnots) {
  if (!Number.isFinite(valueKnots)) return;
  const latIndex = targetIndex(lat, MIN_LAT, LAT_COUNT);
  const lonIndex = targetIndex(normalizeLon(lon), MIN_LON, LON_COUNT);
  if (latIndex < 0 || lonIndex < 0) return;
  const index = fieldIndex(month, latIndex, lonIndex, component);
  accumulator.sum[index] += valueKnots;
  accumulator.count[index] += 1;
}

async function addWind(accumulator) {
  // CCMP V2 monthly grid: 0.25°. Sample every 5° across the Atlantic.
  const west = '[0:1:381][73:20:573][1040:20:1420]'; // ~60S..65N, 100W..5W
  const east = '[0:1:381][73:20:573][0:20:120]';     // Greenwich..30E
  for (const subset of [west, east]) {
    const rows = await fetchRows(WIND_URL, `uwnd${subset},vwnd${subset}`);
    for (const row of rows) {
      const month = new Date(row.time).getUTCMonth();
      addSample(accumulator, month, row.latitude, row.longitude, WIND_E, row.uwnd * MS_TO_KNOTS);
      addSample(accumulator, month, row.latitude, row.longitude, WIND_N, row.vwnd * MS_TO_KNOTS);
    }
  }
}

async function addCurrents(accumulator) {
  // OSCAR archive: ~5-day, 1/3°. A 6-step temporal stride gives a compact
  // ~monthly sample over 1992-2018; samples are grouped by calendar month and
  // averaged across years. Spatial stride 15 corresponds to ~5°.
  const subset = '[0:6:1878][0][45:15:420][720:15:1110]';
  const rows = await fetchRows(CURRENT_URL, `u${subset},v${subset}`);
  for (const row of rows) {
    const month = new Date(row.time).getUTCMonth();
    addSample(accumulator, month, row.latitude, row.longitude, CURRENT_E, row.u * MS_TO_KNOTS);
    addSample(accumulator, month, row.latitude, row.longitude, CURRENT_N, row.v * MS_TO_KNOTS);
  }
}

function finalize(accumulator) {
  const packed = new Int16Array(accumulator.sum.length);
  for (let index = 0; index < packed.length; index += 1) {
    if (accumulator.count[index] === 0) {
      packed[index] = MISSING;
      continue;
    }
    const mean = accumulator.sum[index] / accumulator.count[index];
    packed[index] = Math.max(-32767, Math.min(32767, Math.round(mean * SCALE)));
  }
  return Buffer.from(packed.buffer).toString('base64');
}

async function main() {
  console.log('Building compact Atlantic wind/current climatology from NOAA ERDDAP…');
  const accumulator = createAccumulator();
  await addWind(accumulator);
  await addCurrents(accumulator);
  const packed = finalize(accumulator);
  const source = `// Generated by scripts/build-world-data.mjs. Do not edit by hand.\nexport const ATLANTIC_CLIMATOLOGY = ${JSON.stringify({
    source: 'CCMP v2 monthly winds + OSCAR 1992-2018 surface currents via NOAA ERDDAP',
    generatedAt: new Date().toISOString(),
    minLat: MIN_LAT,
    maxLat: MAX_LAT,
    minLon: MIN_LON,
    maxLon: MAX_LON,
    stepDeg: STEP,
    latCount: LAT_COUNT,
    lonCount: LON_COUNT,
    months: MONTHS,
    scale: SCALE,
    missing: MISSING,
    packed,
  })} as const;\n`;
  await writeFile(OUTPUT, source, 'utf8');
  console.log(`Wrote ${OUTPUT.pathname} (${Math.round(packed.length / 1024)} KiB base64 before JS compression).`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
